"""Synthesise the narration with Kokoro and lay the lines out on one timeline (gaps from script.json).
Writes out/vo/<id>.wav (48 kHz mono), out/vo.wav (whole narration) and out/layout.json + layout.js (global seconds).
Run: KOKORO_MODEL=../.models/kokoro/kokoro-v1.0.onnx KOKORO_VOICES=../.models/kokoro/voices-v1.0.bin ../.venv/bin/python make_vo.py
"""
import json, os
import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
SR = 48000
cfg = json.load(open(os.path.join(HERE, "script.json"), encoding="utf-8"))
k = Kokoro(os.environ["KOKORO_MODEL"], os.environ["KOKORO_VOICES"])
os.makedirs(os.path.join(HERE, "out", "vo"), exist_ok=True)

def synth(text):
    x, sr = k.create(text, voice=cfg["voice"], speed=cfg["speed"], lang="en-us")
    x = x.astype(np.float32)
    idx = np.where(np.abs(x) > 0.004)[0]
    x = x[idx[0]: idx[-1] + 1]
    n = int(len(x) * SR / sr)
    y = np.interp(np.linspace(0, len(x) - 1, n), np.arange(len(x)), x).astype(np.float32)
    f = int(0.012 * SR); y[:f] *= np.linspace(0, 1, f); y[-f:] *= np.linspace(1, 0, f)
    return y

t = cfg["lead_in"]; lines = []; clips = []
for ln in cfg["lines"]:
    t += ln["gap"]
    y = synth(ln["text"]); d = len(y) / SR
    sf.write(os.path.join(HERE, "out", "vo", ln["id"] + ".wav"), y, SR)
    lines.append({"id": ln["id"], "text": ln["text"], "start": round(t, 3), "dur": round(d, 3), "end": round(t + d, 3)})
    clips.append((t, y)); print(f'{ln["id"]:4s} {t:6.2f} +{d:5.2f}  {ln["text"]}')
    t += d
total = round(t + cfg["tail"], 3)
mix = np.zeros(int(total * SR) + 1, np.float32)
for s, y in clips: i = int(round(s * SR)); mix[i:i + len(y)] += y
sf.write(os.path.join(HERE, "out", "vo.wav"), mix, SR)
layout = {"total": total, "lines": lines}
json.dump(layout, open(os.path.join(HERE, "out", "layout.json"), "w"), indent=1)
open(os.path.join(HERE, "src", "layout.js"), "w").write("// generated by make_vo.py\nexport const LAYOUT = " + json.dumps(layout, indent=1) + ";\n")
print("TOTAL", total)
