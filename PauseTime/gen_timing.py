"""out/vo_timing.json + out/words.json -> timing.js (window.VO, window.WORDS) for the page."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(H, "out", "vo_timing.json"))); W = json.load(open(os.path.join(H, "out", "words.json")))
vo = {"total": T["total"], "lines": {l["id"]: {"s": l["start"], "e": l["end"], "text": l["text"]} for l in T["lines"]}}
open(os.path.join(H, "timing.js"), "w").write("// generated by gen_timing.py\nwindow.VO = " + json.dumps(vo) + ";\nwindow.WORDS = " + json.dumps(W) + ";\n")
print("ok", T["total"])
