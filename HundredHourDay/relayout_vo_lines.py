"""Regenerate the named narration lines (same voice/speed/pipeline as make_vo_full.py) after editing their text in script.json,
and SHIFT the timeline to fit: every later line in the same chapter and the chapter duration move by the length change, and all
later chapters move with it. Gaps between lines are kept. Use this when a line grows or shrinks; revise_vo_lines.py keeps starts fixed.
Chapter visuals and cue builders derive their beats from LAYOUT, so re-run the cue builders afterwards.
Usage: python3 relayout_vo_lines.py h4 w4 o2   (needs KOKORO_MODEL / KOKORO_VOICES like make_vo_full.py)
"""
import json, os, sys
import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL = os.environ["KOKORO_MODEL"]; VOICES = os.environ["KOKORO_VOICES"]
OUT_SR = 48000
cfg = json.load(open(os.path.join(HERE, "script.json"), encoding="utf-8"))
layout = json.load(open(os.path.join(HERE, "out", "layout.json"), encoding="utf-8"))
text_of = {ln["id"]: ln["text"] for ch in cfg["chapters"] for ln in ch["lines"]}
k = Kokoro(MODEL, VOICES)

def synth(text):
    samples, sr = k.create(text, voice=cfg["voice"], speed=cfg["speed"], lang="en-us")
    samples = samples.astype(np.float32)
    idx = np.where(np.abs(samples) > 0.004)[0]
    samples = samples[idx[0]: idx[-1] + 1]
    n_out = int(len(samples) * OUT_SR / sr)
    x = np.interp(np.linspace(0, len(samples) - 1, n_out), np.arange(len(samples)), samples).astype(np.float32)
    f = int(0.012 * OUT_SR)
    x[:f] *= np.linspace(0, 1, f); x[-f:] *= np.linspace(1, 0, f)
    return x

chapters = [c for c, v in layout.items() if isinstance(v, dict) and "vo" in v]
for lid in sys.argv[1:]:
    chid, i = next((c, i) for c in chapters for i, l in enumerate(layout[c]["vo"]) if l["id"] == lid)
    ch = layout[chid]; ln = ch["vo"][i]
    x = synth(text_of[lid]); d = len(x) / OUT_SR; delta = d - ln["dur"]
    sf.write(os.path.join(HERE, "out", "vo", f"{lid}.wav"), x, OUT_SR)
    ln["text"] = text_of[lid]; ln["dur"] = round(d, 3); ln["end"] = round(ln["start"] + d, 3)
    for later in ch["vo"][i + 1:]:
        later["start"] = round(later["start"] + delta, 3); later["end"] = round(later["end"] + delta, 3)
    ch["dur"] = round(ch["dur"] + delta, 3)
    print(f"{lid} ({chid}): {d - delta:.3f} -> {d:.3f} s ({delta:+.3f}); chapter dur {ch['dur']}")

cursor = 0.0
for c in chapters:
    layout[c]["start"] = round(cursor, 3); cursor += layout[c]["dur"]
layout["total"] = round(cursor, 3)
print("TOTAL", layout["total"])

json.dump(layout, open(os.path.join(HERE, "out", "layout.json"), "w"), indent=1)
with open(os.path.join(HERE, "layout.js"), "w", encoding="utf-8") as fh:
    fh.write("// generated by make_vo_full.py — chapter start/dur (global seconds) and VO line times (LOCAL to chapter)\n")
    fh.write("const LAYOUT = " + json.dumps(layout, indent=1) + ";\n")
    fh.write("if (typeof module !== 'undefined') module.exports = LAYOUT;\n")
