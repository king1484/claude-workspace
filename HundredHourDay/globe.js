  function renderEarth(e, n, o) {
    const u32 = e.u32, HF = C.HF, LC = C.LC, LI = C.LI, CL = C.CL, TR = C.TR, OC = C.OC, RW = C.RW;
    const tilt = o.lat * DEG, cosT = Math.cos(tilt), sinT = Math.sin(tilt);
    const dl = (o.sunLon - o.lon) * DEG, sla = o.sunLat * DEG;
    const SX = Math.cos(sla) * Math.sin(dl), SY = Math.sin(sla), SZ = Math.cos(sla) * Math.cos(dl);
    let HX = SX, HY = SY + sinT, HZ = SZ + cosT; { const hl = Math.hypot(HX, HY, HZ) || 1; HX /= hl; HY /= hl; HZ /= hl; }
    const half = n * 0.5, invRy = 1 / o.ryScale;
    const ubase = (((o.lon + 180) / 360) * W1) % W1, K = W1 / (2 * PI);
    const cloudsK = o.clouds, atmo = o.atmo, lights = o.nightLights;
    const cshift = (o.tNow * 0.9) / 360 * W1;                      // clouds drift ~0.9 deg/s relative to ground
    const pxU = 1 / (half * 0.5 * DEG);                          // units(0.5deg) per internal pixel at the disc centre
    const ASH = ASN / 2;
    for (let j = 0; j < n; j++) {
      const yy = -((j + 0.5 - half) / half) * invRy, yy2 = yy * yy;
      if (yy2 > 1.05) continue;
      const xl = Math.sqrt(1.05 - yy2);
      const i0 = Math.max(0, Math.floor(half - xl * half)), i1 = Math.min(n - 1, Math.ceil(half + xl * half));
      for (let i = i0; i <= i1; i++) {
        let xx = (i + 0.5 - half) / half, yv = yy, rr = xx * xx + yy2;
        if (rr > 1) { const s = 1 / Math.sqrt(rr); xx *= s; yv *= s; rr = 1; }
        const nz = Math.sqrt(1 - rr);
        const Py = yv * cosT + nz * sinT, Pz = nz * cosT - yv * sinT, Px = xx;
        // texture coords
        let uRaw = ubase + Math.atan2(Px, Pz) * K; if (uRaw < 0) uRaw += W1; else if (uRaw >= W1) uRaw -= W1;
        let vRaw;
        if (Py > -0.985 && Py < 0.985) { const ka = (Py + 1) * ASH, kf = ka | 0; vRaw = RW[kf] + (RW[kf + 1] - RW[kf]) * (ka - kf); }
        else vRaw = (0.5 - Math.asin(Py < -1 ? -1 : Py > 1 ? 1 : Py) / PI) * H1;
        let u = uRaw - 0.5; if (u < 0) u += W1;
        let v = vRaw - 0.5; if (v < 0) v = 0; else if (v > H1 - 1.001) v = H1 - 1.001;
        const i0t = u | 0, fu = u - i0t, j0t = v | 0, fv = v - j0t, id = j0t * S1 + i0t;
        const h = (HF[id] * (1 - fu) + HF[id + 1] * fu) * (1 - fv) + (HF[id + S1] * (1 - fu) + HF[id + S1 + 1] * fu) * fv;
        const tr = TR[j0t] * (1 - fv) + TR[j0t + 1] * fv;
        const ev = h - tr;
        const aa = 0.5 * pxU / (0.18 + nz);
        let al = ev >= aa ? 1 : ev <= -aa ? 0 : (ev + aa) / (2 * aa); al = al * al * (3 - 2 * al);
        let r, g, b;
        if (al > 0) {
          const ci = ((vRaw * 1.42222) | 0) * CW + ((uRaw * 1.42222) | 0), lcv = LC[ci];
          r = lcv & 255; g = (lcv >> 8) & 255; b = (lcv >> 16) & 255;
          if (ev < 1.6) { const kk = (1.6 - ev) * 0.09; r += 22 * kk; g += 18 * kk; b += 6 * kk; }
        }
        if (al < 1) {
          let dep = tr - h; dep = dep < 0 ? 0 : dep; let oi = (dep * 4.25) | 0; if (oi > 255) oi = 255;
          const ov = OC[oi], orr = ov & 255, og = (ov >> 8) & 255, ob = (ov >> 16) & 255;
          if (al > 0) { r = orr + (r - orr) * al; g = og + (g - og) * al; b = ob + (b - ob) * al; } else { r = orr; g = og; b = ob; }
        }
        // clouds
        let cl = 0;
        if (cloudsK > 0.001) {
          let cu = uRaw - cshift; if (cu < 0) cu += W1; cu -= 0.5; if (cu < 0) cu += W1;
          const ci0 = cu | 0, cfu = cu - ci0, cid = j0t * S1 + ci0;
          const ca = ((CL[cid] * (1 - cfu) + CL[cid + 1] * cfu) * (1 - fv) + (CL[cid + S1] * (1 - cfu) + CL[cid + S1 + 1] * cfu) * fv) * (1 / 255);
          cl = ca * cloudsK * 0.88;
          r += (252 - r) * cl; g += (253 - g) * cl; b += (255 - b) * cl;
        }
        // lighting
        const dot = Px * SX + Py * SY + Pz * SZ;
        let t = (dot + 0.07) * 3.1; const dm = t <= 0 ? 0 : t >= 1 ? 1 : t * t * (3 - 2 * t);
        let dd = dot > 0 ? dot : 0; dd = dd * (1.35 - 0.35 * dd);
        const shade = 0.60 + 0.50 * dd;
        const limb = 0.80 + 0.20 * nz;
        let dr = r * shade * limb, dg = g * shade * limb, db = b * shade * limb;
        const nr = r * 0.13 + 4, ng = g * 0.15 + 9, nb = b * 0.22 + 30;
        r = nr + (dr - nr) * dm; g = ng + (dg - ng) * dm; b = nb + (db - nb) * dm;
        // warm sunset band at the terminator
        const bb = (dot - 0.05) * 9.5, bw = bb * bb;
        if (bw < 9) {
          const fall = 1 / ((1 + bw) * (1 + bw));
          const sb = fall * (0.18 + 0.82 * dm);          // only glows where the surface is (partly) lit
          r = r * (1 + 0.30 * sb) + 34 * sb; g = g * (1 - 0.04 * sb) + 9 * sb; b = b * (1 - 0.30 * sb);
        }
        // city lights
        if (lights && dm < 0.85 && al > 0.5) {
          const L = (LI[id] * (1 - fu) + LI[id + 1] * fu) * (1 - fv) + (LI[id + S1] * (1 - fu) + LI[id + S1 + 1] * fu) * fv;
          if (L > 5) { const k = (L / 255) * (1 - dm) * (1 - cl * 0.8) * 1.15; r += k * 255; g += k * 196; b += k * 96; }
        }
        // ocean specular glint
        if (al < 0.5 && dm > 0.2) {
          const nh = Px * HX + Py * HY + Pz * HZ;
          if (nh > 0.6) {
            let sp = (nh - 0.6) * 2.5; sp = sp * sp * 0.07;
            if (nh > 0.96) { let s2 = nh * nh; s2 *= s2; s2 *= s2; s2 *= s2; s2 *= s2; s2 *= s2; s2 *= s2; sp += s2 * 0.75; }
            sp *= (1 - cl) * dm * (1 - al * 2);
            r += sp * 255; g += sp * 244; b += sp * 215;
          }
        }
        // atmosphere inner rim
        if (atmo > 0) {
          const rim = 1 - nz, r3 = rim * rim * rim;
          const dayk = 0.16 + 0.84 * dm;
          const ak = r3 * atmo * dayk;
          r += ak * 52; g += ak * 118; b += ak * 215;
          const wk = r3 * atmo * (bw < 9 ? 1 / ((1 + bw) * (1 + bw)) : 0) * 0.7;
          r += wk * 130; g += wk * 62; b += wk * 6;
        }
        u32[j * n + i] = (255 << 24) | ((b > 255 ? 255 : b < 0 ? 0 : b | 0) << 16) | ((g > 255 ? 255 : g < 0 ? 0 : g | 0) << 8) | (r > 255 ? 255 : r < 0 ? 0 : r | 0);
      }
    }
  }

