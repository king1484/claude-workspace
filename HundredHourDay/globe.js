  function dial(g, cx, cy, r, o) {
    o = o || {};
    const pop = num(o.pop, 1), k = clampf(num(o.k, 1)), from = num(o.from, 1670), to = num(o.to, 417), vmin = num(o.min, 0), vmax = num(o.max, 1800), tNow = num(o.tNow, 0);
    const bk = (p) => { p = clampf(p); const c1 = 1.70158, c3 = c1 + 1; return 1 + c3 * Math.pow(p - 1, 3) + c1 * Math.pow(p - 1, 2); };
    const s = pop <= 1 ? bk(pop) : pop;
    if (s <= 0.002) return;
    const val = mix(from, to, sm(k) * 0.0 + (k < 0.5 ? 4 * k * k * k : 1 - Math.pow(-2 * k + 2, 3) / 2)); // easeInOutCubic
    const A0 = 135 * DEG, SW = 270 * DEG, frac = (v) => clampf((v - vmin) / (vmax - vmin));
    const col = (f) => { // f: 0 = low (cyan) .. 1 = high (red)
      const stops = [[0, 70, 232, 255], [0.45, 120, 255, 200], [0.62, 255, 214, 70], [1, 255, 58, 58]];
      let i = 0; while (i < stops.length - 2 && f > stops[i + 1][0]) i++;
      const a = stops[i], b = stops[i + 1], t = clampf((f - a[0]) / (b[0] - a[0]));
      return [mix(a[1], b[1], t), mix(a[2], b[2], t), mix(a[3], b[3], t)];
    };
    const rgb = (c, a) => `rgba(${c[0] | 0},${c[1] | 0},${c[2] | 0},${a === undefined ? 1 : a})`;
    g.save(); g.translate(cx, cy); g.scale(s, s); g.globalAlpha = clampf(pop * 3);
    // drop shadow + glow
    g.fillStyle = 'rgba(0,0,0,0.30)'; g.beginPath(); g.ellipse(r * 0.04, r * 0.1, r * 1.02, r * 1.0, 0, 0, PI * 2); g.fill();
    // bezel
    const bz = g.createLinearGradient(-r, -r, r, r); bz.addColorStop(0, '#8d97bb'); bz.addColorStop(0.45, '#2c3454'); bz.addColorStop(1, '#0e1226');
    g.fillStyle = bz; g.beginPath(); g.arc(0, 0, r, 0, PI * 2); g.fill();
    g.lineWidth = r * 0.02; g.strokeStyle = 'rgba(255,255,255,0.35)'; g.beginPath(); g.arc(0, 0, r * 0.985, 0, PI * 2); g.stroke();
    const fg = g.createRadialGradient(-r * 0.2, -r * 0.3, r * 0.05, 0, 0, r * 0.9);
    fg.addColorStop(0, '#26336a'); fg.addColorStop(0.6, '#121a42'); fg.addColorStop(1, '#090d28');
    g.fillStyle = fg; g.beginPath(); g.arc(0, 0, r * 0.89, 0, PI * 2); g.fill();
    g.lineWidth = r * 0.012; g.strokeStyle = 'rgba(0,0,0,0.6)'; g.stroke();
    // colour arc (dim full range, bright up to the needle)
    const SEG = 90, rin = r * 0.62, rout = r * 0.70;
    g.lineCap = 'butt';
    for (let i = 0; i < SEG; i++) {
      const f0 = i / SEG, f1 = (i + 1.05) / SEG, c = col((f0 + f1) / 2);
      const lit = (f0 + 0.5 / SEG) <= frac(val);
      g.strokeStyle = rgb(c, lit ? 1 : 0.22); g.lineWidth = rout - rin;
      g.beginPath(); g.arc(0, 0, (rin + rout) / 2, A0 + SW * f0, A0 + SW * f1); g.stroke();
    }
    // ticks
    const minor = Math.round((vmax - vmin) / 50), majorEvery = 4;
    for (let i = 0; i <= minor; i++) {
      const a = A0 + SW * i / minor, mj = i % majorEvery === 0, r0 = r * (mj ? 0.74 : 0.78), r1 = r * 0.855;
      g.strokeStyle = mj ? 'rgba(255,255,255,0.95)' : 'rgba(210,225,255,0.55)'; g.lineWidth = r * (mj ? 0.028 : 0.013); g.lineCap = 'round';
      g.beginPath(); g.moveTo(Math.cos(a) * r0, Math.sin(a) * r0); g.lineTo(Math.cos(a) * r1, Math.sin(a) * r1); g.stroke();
    }
    // chevrons (4, slowing down): red -> cyan
    for (let i = 0; i < 4; i++) {
      const f = i / 3, c = col(1 - f), y = r * (0.26 + i * 0.105), w = r * 0.20 * (1 - i * 0.08);
      const lit = sm(k * 5.2 - i * 0.55) , pul = 0.55 + 0.45 * Math.sin(tNow * 7 - i * 1.0);
      const al = 0.16 + 0.84 * lit * (0.55 + 0.45 * pul);
      g.lineJoin = 'round'; g.lineCap = 'round';
      g.strokeStyle = `rgba(0,0,0,${0.5 * al})`; g.lineWidth = r * 0.062; g.beginPath(); g.moveTo(-w, y - r * 0.04); g.lineTo(0, y + r * 0.04); g.lineTo(w, y - r * 0.04); g.stroke();
      g.strokeStyle = rgb(c, al); g.lineWidth = r * 0.038; g.stroke();
    }
    // needle
    const ang = A0 + SW * frac(val) + (k > 0.02 && k < 0.98 ? Math.sin(tNow * 47) * 0.012 : 0), nc = col(frac(val));
    g.save(); g.rotate(ang);
    g.fillStyle = rgb(nc, 0.25); g.beginPath(); g.moveTo(0, -r * 0.07); g.lineTo(r * 0.70, -r * 0.02); g.lineTo(r * 0.70, r * 0.02); g.lineTo(0, r * 0.07); g.closePath(); g.fill();
    const ng = g.createLinearGradient(0, 0, r * 0.72, 0); ng.addColorStop(0, '#ffffff'); ng.addColorStop(1, rgb(nc));
    g.fillStyle = 'rgba(0,0,0,0.5)'; g.beginPath(); g.moveTo(-r * 0.15, -r * 0.034); g.lineTo(r * 0.72, -r * 0.008); g.lineTo(r * 0.72, r * 0.008); g.lineTo(-r * 0.15, r * 0.034); g.closePath(); g.fill();
    g.fillStyle = ng; g.beginPath(); g.moveTo(-r * 0.13, -r * 0.03); g.lineTo(r * 0.70, -r * 0.0055); g.lineTo(r * 0.70, r * 0.0055); g.lineTo(-r * 0.13, r * 0.03); g.closePath(); g.fill();
    g.restore();
    const hub = g.createRadialGradient(-r * 0.02, -r * 0.02, r * 0.01, 0, 0, r * 0.1); hub.addColorStop(0, '#fff'); hub.addColorStop(1, '#6b7599');
    g.fillStyle = hub; g.beginPath(); g.arc(0, 0, r * 0.075, 0, PI * 2); g.fill(); g.strokeStyle = 'rgba(0,0,0,0.5)'; g.lineWidth = r * 0.01; g.stroke();
    // glass reflection
    g.globalAlpha *= 0.14; g.fillStyle = '#fff'; g.beginPath(); g.ellipse(-r * 0.22, -r * 0.42, r * 0.5, r * 0.26, -0.5, 0, PI * 2); g.fill();
    g.restore();
    // pop flash ring
    if (pop > 0 && pop < 0.9) { g.save(); g.globalAlpha = (1 - pop / 0.9) * 0.6; g.lineWidth = r * 0.06; g.strokeStyle = '#9fe9ff'; g.beginPath(); g.arc(cx, cy, r * (1 + pop * 0.35), 0, PI * 2); g.stroke(); g.restore(); }
  }

