  let THERM = null;
  function lutOf(stops, N) {
    const out = new Uint32Array(N);
    for (let k = 0; k < N; k++) {
      const t = k / (N - 1); let s = 0; while (s < stops.length - 2 && t > stops[s + 1][0]) s++;
      const a = stops[s], b = stops[s + 1], f = clampf((t - a[0]) / (b[0] - a[0]));
      out[k] = (255 << 24) | (clampi(mix(a[3], b[3], f)) << 16) | (clampi(mix(a[2], b[2], f)) << 8) | clampi(mix(a[1], b[1], f));
    }
    return out;
  }
  function thermLuts() {
    if (THERM) return THERM;
    // t = (dot + 1)/2 : 0 = antipode (deep night) .. 0.5 terminator .. 1 = subsolar
    const ocean = [[0, 14, 40, 120], [0.18, 24, 60, 170], [0.36, 50, 100, 225], [0.46, 110, 150, 255], [0.495, 255, 150, 220], [0.52, 255, 190, 90], [0.6, 255, 140, 40], [0.78, 245, 70, 36], [0.93, 236, 38, 38], [1, 255, 196, 110]];
    const land = [[0, 8, 24, 84], [0.18, 16, 40, 128], [0.36, 36, 76, 190], [0.46, 84, 118, 235], [0.495, 255, 140, 200], [0.52, 255, 172, 70], [0.6, 235, 116, 28], [0.78, 205, 50, 30], [0.93, 168, 24, 30], [1, 255, 170, 90]];
    THERM = { ocean: lutOf(ocean, 512), land: lutOf(land, 512) };
    return THERM;
  }
  function renderThermal(e, n, q) {
    const u32 = e.u32, HF = C.HF, RW = C.RW, TR = C.TR, L = thermLuts();
    const tilt = q.lat * DEG, cosT = Math.cos(tilt), sinT = Math.sin(tilt);
    const dl = (q.sunLon - q.lon) * DEG, sla = q.sunLat * DEG;
    const SX = Math.cos(sla) * Math.sin(dl), SY = Math.sin(sla), SZ = Math.cos(sla) * Math.cos(dl);
    const half = n * 0.5, ubase = (((q.lon + 180) / 360) * W1) % W1, K = W1 / (2 * PI), pxU = 1 / (half * 0.5 * DEG), ASH = ASN / 2;
    for (let j = 0; j < n; j++) {
      const yy = -((j + 0.5 - half) / half), yy2 = yy * yy;
      if (yy2 > 1.05) continue;
      const xl = Math.sqrt(1.05 - yy2), i0 = Math.max(0, Math.floor(half - xl * half)), i1 = Math.min(n - 1, Math.ceil(half + xl * half));
      for (let i = i0; i <= i1; i++) {
        let xx = (i + 0.5 - half) / half, yv = yy, rr = xx * xx + yy2;
        if (rr > 1) { const s = 1 / Math.sqrt(rr); xx *= s; yv *= s; rr = 1; }
        const nz = Math.sqrt(1 - rr), Py = yv * cosT + nz * sinT, Pz = nz * cosT - yv * sinT, Px = xx;
        let uRaw = ubase + Math.atan2(Px, Pz) * K; if (uRaw < 0) uRaw += W1; else if (uRaw >= W1) uRaw -= W1;
        let vRaw;
        if (Py > -0.985 && Py < 0.985) { const ka = (Py + 1) * ASH, kf = ka | 0; vRaw = RW[kf] + (RW[kf + 1] - RW[kf]) * (ka - kf); } else vRaw = (0.5 - Math.asin(Py < -1 ? -1 : Py > 1 ? 1 : Py) / PI) * H1;
        let u = uRaw - 0.5; if (u < 0) u += W1; let v = vRaw - 0.5; if (v < 0) v = 0; else if (v > H1 - 1.001) v = H1 - 1.001;
        const i0t = u | 0, fu = u - i0t, j0t = v | 0, fv = v - j0t, id = j0t * S1 + i0t;
        const h = (HF[id] * (1 - fu) + HF[id + 1] * fu) * (1 - fv) + (HF[id + S1] * (1 - fu) + HF[id + S1 + 1] * fu) * fv;
        const ev = h - (TR[j0t] * (1 - fv) + TR[j0t + 1] * fv), aa = 0.5 * pxU / (0.18 + nz);
        let al = ev >= aa ? 1 : ev <= -aa ? 0 : (ev + aa) / (2 * aa); al = al * al * (3 - 2 * al);
        const dot = Px * SX + Py * SY + Pz * SZ;
        let ti = ((dot + 1) * 255.5) | 0; if (ti < 0) ti = 0; else if (ti > 511) ti = 511;
        const oc = L.ocean[ti], lc = L.land[ti];
        let r = oc & 255, g = (oc >> 8) & 255, b = (oc >> 16) & 255;
        if (al > 0) { const lr = lc & 255, lg = (lc >> 8) & 255, lb = (lc >> 16) & 255; r += (lr - r) * al; g += (lg - g) * al; b += (lb - b) * al; }
        // coast highlight line
        const ce = ev < 0 ? -ev : ev; if (ce < 1.1) { const kk = (1.1 - ce) * 0.28; r += (255 - r) * kk * 0.6; g += (240 - g) * kk * 0.6; b += (220 - b) * kk * 0.6; }
        // limb shading and rim
        const limb = 0.72 + 0.28 * nz; r *= limb; g *= limb; b *= limb;
        const rim = 1 - nz, r3 = rim * rim * rim;
        r += r3 * 40; g += r3 * 20; b += r3 * 55;
        u32[j * n + i] = (255 << 24) | (clampi(b) << 16) | (clampi(g) << 8) | clampi(r);
      }
    }
  }
  function chevron(g, x, y, s, dir, w) {
    g.beginPath(); g.moveTo(x - dir * s * 0.55, y - s); g.lineTo(x + dir * s * 0.45, y); g.lineTo(x - dir * s * 0.55, y + s); g.lineWidth = w; g.stroke();
  }
  function dayNightSplit(g, cx, cy, R, o) {
    build();
    o = o || {};
    const q = normOpts({ lon: num(o.lon, 25), lat: num(o.lat, 12), sunLon: num(o.sunLon, num(o.lon, 25) - 78), sunLat: num(o.sunLat, 6), sea: o.sea, tNow: o.tNow });
    const wind = clampf(num(o.wind, 0)), hur = clampf(num(o.hurricane, 0)), tNow = q.tNow;
    const tear = o.tear !== undefined ? clampf(num(o.tear, 0)) : sm((hur - 0.3) / 0.7);
    const pres = sm(hur / 0.22);
    const tilt = q.lat * DEG, dl = (q.sunLon - q.lon) * DEG, sla = q.sunLat * DEG;
    const Sx = Math.cos(sla) * Math.sin(dl), Sy0 = Math.sin(sla), Sz0 = Math.cos(sla) * Math.cos(dl);
    const Svy = Sy0 * Math.cos(tilt) - Sz0 * Math.sin(tilt);
    const hot = Sx >= 0 ? 1 : -1;                      // screen side of the day hemisphere
    g.save();
    // outer glows: warm on the hot side, cold on the other
    const gg = g.createLinearGradient(cx - R * 1.3, 0, cx + R * 1.3, 0);
    const wA = 'rgba(255,120,50,0.50)', cA = 'rgba(70,140,255,0.45)';
    gg.addColorStop(0, hot < 0 ? wA : cA); gg.addColorStop(0.45, hot < 0 ? 'rgba(255,150,70,0.18)' : 'rgba(90,160,255,0.16)'); gg.addColorStop(0.55, hot < 0 ? 'rgba(90,160,255,0.16)' : 'rgba(255,150,70,0.18)'); gg.addColorStop(1, hot < 0 ? cA : wA);
    g.save(); g.globalCompositeOperation = 'lighter';
    const rg = g.createRadialGradient(cx, cy, R * 0.92, cx, cy, R * 1.28); rg.addColorStop(0, 'rgba(255,255,255,0.9)'); rg.addColorStop(1, 'rgba(255,255,255,0)');
    // glow ring composed with the horizontal tint through an offscreen sprite
    const gt = C.glowTmp, gx = gt.getContext('2d');
    gx.globalCompositeOperation = 'source-over'; gx.clearRect(0, 0, 256, 256); gx.drawImage(C.glowBase, 0, 0);
    gx.globalCompositeOperation = 'source-in'; const hg = gx.createLinearGradient(0, 0, 256, 0);
    hg.addColorStop(0, hot < 0 ? '#ff6a2c' : '#4f8cff'); hg.addColorStop(0.46, hot < 0 ? '#ff9a4a' : '#6aa8ff'); hg.addColorStop(0.54, hot < 0 ? '#6aa8ff' : '#ff9a4a'); hg.addColorStop(1, hot < 0 ? '#4f8cff' : '#ff6a2c');
    gx.fillStyle = hg; gx.fillRect(0, 0, 256, 256); gx.globalCompositeOperation = 'source-over';
    g.globalAlpha = 0.95; g.drawImage(gt, cx - R / 0.70, cy - R / 0.70, 2 * R / 0.70, 2 * R / 0.70); g.restore();
    // sphere
    const sc = Math.min(1, 300 / (2 * R)), n = Math.max(48, Math.ceil(2 * R * sc)), e = getImg(n);
    q.ryScale = 1; fillThr(0); renderThermal(e, n, q); e.x.putImageData(e.id, 0, 0);
    g.save(); g.beginPath(); g.arc(cx, cy, R, 0, PI * 2); g.clip(); g.imageSmoothingEnabled = true; g.imageSmoothingQuality = 'high';
    g.drawImage(e.cv, cx - R, cy - R, 2 * R, 2 * R);
    // terminator glow (great circle is an ellipse arc): semi-axis in x = |Sz| ... project the terminator
    drawTerminator(g, cx, cy, R, Sx, Svy, Sy0, Sz0, tilt, tNow);
    g.restore();
    // limb line
    g.lineWidth = Math.max(2, R * 0.008); g.strokeStyle = 'rgba(255,255,255,0.28)'; g.beginPath(); g.arc(cx, cy, R * 0.996, 0, PI * 2); g.stroke();
    // wind
    if (wind > 0.01) drawWind(g, cx, cy, R, hot, wind, tNow);
    if (hur > 0.01) {
      g.save(); g.beginPath(); g.arc(cx, cy, R * 0.97, 0, PI * 2); g.clip();
      drawHurricane(g, cx + hot * R * 0.34, cy - R * 0.12, R * 0.36, hur, pres, tear, hot, tNow);
      g.restore();
    }
    g.restore();
  }
  function drawTerminator(g, cx, cy, R, Sx, Svy, Sy0, Sz0, tilt, tNow) {
    // terminator = points with P.S = 0. In view space the sun vector is (vx,vy,vz); the circle projects to an ellipse
    const vx = Sx, vy = Svy, vz = Sy0 * Math.sin(tilt) + Sz0 * Math.cos(tilt);
    const N = 90, pts = [];
    // basis of the plane perpendicular to the sun vector
    let ax = -vy, ay = vx, az = 0; let al = Math.hypot(ax, ay) || 1; if (al < 1e-4) { ax = 1; ay = 0; az = 0; al = 1; } ax /= al; ay /= al;
    const bx = vy * az - vz * ay, by = vz * ax - vx * az, bz = vx * ay - vy * ax;
    for (let i = 0; i <= N; i++) { const a = i / N * PI * 2, c = Math.cos(a), s = Math.sin(a); const x = ax * c + bx * s, y = ay * c + by * s, z = az * c + bz * s; pts.push([cx + x * R, cy - y * R, z]); }
    g.save(); g.globalCompositeOperation = 'lighter'; g.lineCap = 'round'; g.lineJoin = 'round';
    for (const [w, a, col] of [[R * 0.10, 0.10, '255,120,200'], [R * 0.05, 0.18, '255,170,230'], [R * 0.018, 0.55, '255,235,250']]) {
      g.lineWidth = w; g.strokeStyle = `rgba(${col},${a})`; g.beginPath(); let pen = false;
      for (const p of pts) { if (p[2] > -0.02) { if (!pen) { g.moveTo(p[0], p[1]); pen = true; } else g.lineTo(p[0], p[1]); } else pen = false; }
      g.stroke();
    }
    g.restore();
  }
  function drawWind(g, cx, cy, R, hot, wind, tNow) {
    g.save();
    g.beginPath(); g.arc(cx, cy, R * 0.985, 0, PI * 2); g.clip();
    g.lineCap = 'round'; g.lineJoin = 'round';
    const rows = [-0.62, -0.38, -0.14, 0.1, 0.34, 0.58];
    for (let ri = 0; ri < rows.length; ri++) {
      const y0 = rows[ri], half = Math.sqrt(Math.max(0.01, 1 - y0 * y0)) * R * 0.92, span = half * 2;
      const spd = 0.22 + 0.05 * (ri % 3), gap = 0.30 * R;
      const cnt = Math.max(2, Math.floor(span / gap));
      for (let k = 0; k < cnt + 1; k++) {
        // travel from the cold side to the hot side
        let f = ((tNow * spd * R / span + k / cnt + ri * 0.17) % 1 + 1) % 1;
        const x = cx - hot * 0 + (hot < 0 ? (half - f * span) : (-half + f * span));
        const dir = hot;
        const edge = Math.min(sm(f * 6), sm((1 - f) * 6));
        const a = edge * wind * 0.95;
        const s = R * (0.05 + 0.025 * wind) * (0.8 + 0.4 * (1 - Math.abs(y0)));
        const y = cy + y0 * R + Math.sin(f * PI * 2 + ri) * R * 0.012;
        const mixT = f; // cold (cyan) -> hot (orange-white)
        const cr = mix(120, 255, mixT), cg = mix(225, 220, mixT), cb = mix(255, 140, mixT);
        g.globalAlpha = a * 0.55; g.strokeStyle = 'rgba(10,20,60,0.9)'; chevron(g, x, y, s, dir, R * 0.034);
        g.globalAlpha = a; g.strokeStyle = `rgb(${cr | 0},${cg | 0},${cb | 0})`; chevron(g, x, y, s, dir, R * 0.02);
        if (wind > 0.5) { g.globalAlpha = a * 0.7; chevron(g, x - dir * s * 0.75, y, s * 0.8, dir, R * 0.014); }
      }
    }
    g.restore();
  }
  function drawHurricane(g, x, y, r, hur, pres, tear, hot, tNow) {
    const fo = 0.78;
    g.save(); g.lineCap = 'round';
    // soft shadow disc
    g.globalAlpha = 0.18 * pres * (1 - tear * 0.6); g.fillStyle = '#300'; g.beginPath(); g.ellipse(x + r * 0.04, y + r * 0.06, r * 1.05, r * 1.05 * fo, 0, 0, PI * 2); g.fill();
    // soft disc of cloud under the arms
    g.globalAlpha = 0.55 * pres * (1 - tear); g.fillStyle = '#e8eefc'; g.beginPath(); g.ellipse(x, y, r * 0.7, r * 0.7 * fo, 0, 0, PI * 2); g.fill();
    const ARMS = 4, NS = 6, SUB = 4;                  // each arm = NS chunks of SUB sub-segments (chunks shear apart when the storm fails)
    const tw = 0.4 + 4.2 * (1 - tear * 0.8), spin = tNow * (1.5 - tear * 1.0);
    g.lineCap = 'round'; g.lineJoin = 'round';
    for (const pass of [0, 1]) {
      for (let a = 0; a < ARMS; a++) {
        for (let s = 0; s < NS; s++) {
          const seed = a * 97 + s * 13, rnd = hash1(seed), rnd2 = hash1(seed + 500), rnd3 = hash1(seed + 900);
          const f0 = s / NS, fm = (s + 0.5) / NS;
          const gone = sm((tear - 0.55 - 0.4 * rnd2) / 0.4) * 0.8;
          const al = pres * (1 - gone);
          if (al < 0.02) continue;
          // wind shear: chunks slide downwind (towards the day side), scatter and tilt as the storm falls apart
          const shx = hot * tear * r * (0.1 + 1.0 * fm * fm + 0.45 * rnd), shy = (rnd3 - 0.5) * r * 0.9 * tear * fm;
          g.beginPath();
          for (let u = 0; u <= SUB; u++) {
            const f = (s + u / SUB * (1 + 0.14 * (1 - tear))) / NS;
            const th = a * (PI * 2 / ARMS) + f * tw + spin, rad = r * (0.12 + 0.88 * Math.pow(f, 0.8));
            const px = x + Math.cos(th) * rad + shx, py = y + Math.sin(th) * rad * fo + shy;
            if (u) g.lineTo(px, py); else g.moveTo(px, py);
          }
          const wd = r * (0.21 - 0.10 * fm) * (1 - 0.4 * tear * fm) * (0.85 + 0.3 * rnd);
          if (pass === 0) { g.globalAlpha = al * 0.45; g.strokeStyle = '#8fa3d0'; g.lineWidth = wd * 1.2; g.save(); g.translate(wd * 0.06, wd * 0.15); g.stroke(); g.restore(); }
          else { g.globalAlpha = al; g.strokeStyle = '#ffffff'; g.lineWidth = wd; g.stroke(); }
        }
      }
    }
    // eye wall + eye (collapses when torn)
    const eyeA = pres * (1 - sm(tear / 0.5));
    if (eyeA > 0.01) {
      g.globalAlpha = eyeA; g.fillStyle = '#ffffff'; g.beginPath(); g.ellipse(x, y, r * 0.30, r * 0.30 * fo, 0, 0, PI * 2); g.fill();
      g.fillStyle = '#c0311f'; g.globalAlpha = eyeA * 0.9; g.beginPath(); g.ellipse(x, y, r * 0.12, r * 0.12 * fo, 0, 0, PI * 2); g.fill();
    }
    g.restore();
  }

