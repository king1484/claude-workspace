    const rg = g.createRadialGradient(cx - R * 0.25, cy - R * 0.3, R * 0.1, cx, cy, R * 1.0);
    rg.addColorStop(0, '#e1b377'); rg.addColorStop(0.7, '#b98650'); rg.addColorStop(1, '#8a5a34'); g.fillStyle = rg; g.fill();
    g.lineWidth = Math.max(2, R * 0.012); g.strokeStyle = '#5a3a22'; g.stroke();
