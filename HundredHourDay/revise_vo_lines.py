"""Regenerate ONLY the named narration lines (same voice/speed/pipeline as make_vo_full.py) after editing their text in script.json,
and patch out/layout.json + layout.js for those lines (text, dur, end). Starts of every line and every chapter duration stay UNCHANGED, so all
chapter timing / cues / picture stay aligned. Refuses a line that would end later than before AND crowd the next line (< 0.2 s gap) or the chapter tail.
Usage: python3 revise_vo_lines.py h2 b4 n4 w2 w4   (needs KOKORO_MODEL / KOKORO_VOICES like make_vo_full.py)
"""
import json, os, sys
import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL = os.environ["KOKORO_MODEL"]; VOICES = os.environ["KOKORO_VOICES"]
OUT_SR = 48000
cfg = json.load(open(os.path.join(HERE, "script.json"), encoding="utf-8"))
layout = json.load(open(os.path.join(HERE, "out", "layout.json"), encoding="utf-8"))
text_of = {ln["id"]: ln["text"] for ch in cfg["chapters"] for ln in ch["lines"]}
k = Kokoro(MODEL, VOICES)

def synth(text):
    samples, sr = k.create(text, voice=cfg["voice"], speed=cfg["speed"], lang="en-us")
    samples = samples.astype(np.float32)
    idx = np.where(np.abs(samples) > 0.004)[0]
    samples = samples[idx[0]: idx[-1] + 1]
    n_out = int(len(samples) * OUT_SR / sr)
    x = np.interp(np.linspace(0, len(samples) - 1, n_out), np.arange(len(samples)), samples).astype(np.float32)
    f = int(0.012 * OUT_SR)
    x[:f] *= np.linspace(0, 1, f); x[-f:] *= np.linspace(1, 0, f)
    return x

for lid in sys.argv[1:]:
    chid, i = next((c, i) for c, v in layout.items() if isinstance(v, dict) and "vo" in v for i, l in enumerate(v["vo"]) if l["id"] == lid)
    ch = layout[chid]; ln = ch["vo"][i]
    x = synth(text_of[lid]); d = len(x) / OUT_SR
    limit = (ch["vo"][i + 1]["start"] if i + 1 < len(ch["vo"]) else ch["dur"] - 1.0) - 0.2
    if ln["start"] + d > limit and ln["start"] + d > ln["end"]:
        raise SystemExit(f"{lid}: new line ends {ln['start'] + d:.3f} > limit {limit:.3f}; shorten the text")
    sf.write(os.path.join(HERE, "out", "vo", f"{lid}.wav"), x, OUT_SR)
    print(f"{lid}: {ln['dur']:.3f} -> {d:.3f} s (start {ln['start']} unchanged, ends {ln['start'] + d:.3f}, next limit {limit:.3f})")
    ln["text"] = text_of[lid]; ln["dur"] = round(d, 3); ln["end"] = round(ln["start"] + d, 3)

json.dump(layout, open(os.path.join(HERE, "out", "layout.json"), "w"), indent=1)
with open(os.path.join(HERE, "layout.js"), "w", encoding="utf-8") as fh:
    fh.write("// generated by make_vo_full.py — chapter start/dur (global seconds) and VO line times (LOCAL to chapter)\n")
    fh.write("const LAYOUT = " + json.dumps(layout, indent=1) + ";\n")
    fh.write("if (typeof module !== 'undefined') module.exports = LAYOUT;\n")
