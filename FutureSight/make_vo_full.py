"""Kokoro VO for the full video -> out/vo/<id>.wav, out/layout.json, layout.js (global LAYOUT).
Hook (chapter 0, 10.8 s) keeps its own audio in out/vo.wav and is placed at t=0.
Run: python3 make_vo_full.py (optional: replaces narration and layout)
"""
import json, os
import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(os.path.expanduser("~"), ".cache", "hyperframes", "tts")
MODEL = os.environ.get("KOKORO_MODEL", os.path.join(CACHE, "models", "kokoro-v1.0.onnx"))
VOICES = os.environ.get("KOKORO_VOICES", os.path.join(CACHE, "voices", "voices-v1.0.bin"))
for env_name, filename in (("KOKORO_MODEL", MODEL), ("KOKORO_VOICES", VOICES)):
    if not os.path.isfile(filename):
        raise FileNotFoundError(f"Missing {filename}. Set {env_name} to the existing model/voices file. "
                                "Use the preserved out/vo WAVs and layout when continuing without new narration.")
OUT_SR = 48000
HOOK_DUR = 10.8

cfg = json.load(open(os.path.join(HERE, "script.json"), encoding="utf-8"))
os.makedirs(os.path.join(HERE, "out", "vo"), exist_ok=True)
k = Kokoro(MODEL, VOICES)

def trim(x, thr=0.004):
    idx = np.where(np.abs(x) > thr)[0]
    return x if len(idx) == 0 else x[idx[0]: idx[-1] + 1]

layout = {"hook": {"start": 0.0, "dur": HOOK_DUR}}
cursor = HOOK_DUR
for ch in cfg["chapters"]:
    t = ch["lead"]
    lines = []
    for ln in ch["lines"]:
        samples, sr = k.create(ln["text"], voice=cfg["voice"], speed=cfg["speed"], lang="en-us")
        samples = trim(samples.astype(np.float32))
        n_out = int(len(samples) * OUT_SR / sr)
        x = np.interp(np.linspace(0, len(samples) - 1, n_out), np.arange(len(samples)), samples).astype(np.float32)
        f = int(0.012 * OUT_SR)
        x[:f] *= np.linspace(0, 1, f); x[-f:] *= np.linspace(1, 0, f)
        d = len(x) / OUT_SR
        t += ln["gap"]
        sf.write(os.path.join(HERE, "out", "vo", f"{ln['id']}.wav"), x, OUT_SR)
        lines.append({"id": ln["id"], "text": ln["text"], "start": round(t, 3), "dur": round(d, 3), "end": round(t + d, 3)})
        t += d
    dur = round(t + cfg["tail"], 3)
    layout[ch["id"]] = {"title": ch["title"], "start": round(cursor, 3), "dur": dur, "vo": lines}
    cursor += dur
layout["total"] = round(cursor, 3)
json.dump(layout, open(os.path.join(HERE, "out", "layout.json"), "w"), indent=1)
with open(os.path.join(HERE, "layout.js"), "w", encoding="utf-8") as fh:
    fh.write("// generated by make_vo_full.py — chapter start/dur (global seconds) and VO line times (LOCAL to chapter)\n")
    fh.write("const LAYOUT = " + json.dumps(layout, indent=1) + ";\n")
    fh.write("if (typeof module !== 'undefined') module.exports = LAYOUT;\n")
for key, v in layout.items():
    if isinstance(v, dict) and "vo" in v:
        print(key, v["title"], "start", v["start"], "dur", v["dur"], "lines", len(v["vo"]))
print("TOTAL", layout["total"], "s =", round(layout["total"] / 60, 2), "min")
